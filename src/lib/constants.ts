import { AppItem, Settings } from '../types';

export function createApp(
  id: string,
  name: string,
  url: string,
  category: string,
  aliases: string[] = [],
  searchUrl?: string
): AppItem {
  let domain = '';
  try {
    domain = new URL(url).hostname.replace(/^www\./, '');
  } catch {
    domain = id;
  }
  return {
    id,
    name,
    domain,
    url,
    category,
    aliases,
    searchUrl,
    custom: false,
    favorite: false,
    lastUsed: null,
  };
}

